import {test,expect} from '@playwright/test';
import {mkdir} from 'node:fs/promises';

test('compact console, persistent sidebar hiding and keyboard/popover controls preserve the board',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');await page.getByRole('button',{name:'＋ Add project',exact:true}).first().click();
 await page.getByLabel('Project name').fill('Orbital / interface fixture');await page.getByRole('button',{name:'Confirm & add project'}).click();
 const names=['Storage persist ledger','Sync peer protocol','Backend mutation validation','UI editor layout','Desktop shell lifecycle','Mobile iOS enrollment','Device enrollment checks','Release CI pipeline'];
 await page.getByRole('button',{name:'Import documents',exact:true}).first().click();
 await page.getByLabel('Markdown or legacy dashboard files').setInputFiles({name:'console-fixture.md',mimeType:'text/markdown',buffer:Buffer.from('# Active work\n'+names.flatMap(name=>Array.from({length:4},(_,i)=>'- ['+(i===0?'x':' ')+'] '+name+' '+(i+1))).join('\n'))});
 await page.getByRole('button',{name:'Preview import',exact:true}).click();await page.getByRole('button',{name:'Apply 32 reviewed tasks',exact:true}).click();
 await expect(page.locator('.task-card.group')).toHaveCount(8);
 const snapshot=async()=>page.evaluate(async()=>{
  const token=document.querySelector<HTMLMetaElement>('meta[name="dashboard-token"]')!.content;
  const headers={'X-Dashboard-Token':token};const projects=await (await fetch('/api/projects',{headers})).json();
  return (await fetch('/api/projects/'+projects.find((p:{name:string})=>p.name==='Orbital / interface fixture').id+'/board',{headers})).json();
 });
 const before=await snapshot();
 const originalWidth=(await page.locator('.view-area').boundingBox())!.width;
 expect((await page.locator('.view-area').boundingBox())!.y).toBeLessThanOrEqual(90);
 await page.getByRole('button',{name:'Hide project sidebar'}).click();
 await expect(page.getByRole('complementary',{name:'Project sidebar'})).toBeHidden();
 expect((await page.locator('.view-area').boundingBox())!.width).toBeGreaterThan(originalWidth+180);
 await page.reload();await expect(page.getByRole('heading',{name:'Orbital / interface fixture'})).toBeVisible();
 await expect(page.getByRole('button',{name:'Show project sidebar'})).toHaveAttribute('aria-expanded','false');
 await expect(page.getByRole('complementary',{name:'Project sidebar'})).toBeHidden();
 await page.getByRole('button',{name:'Show project sidebar'}).focus();await page.keyboard.press('Control+b');
 await expect(page.getByRole('button',{name:'Hide project sidebar'})).toHaveAttribute('aria-expanded','true');
 await page.getByLabel('Search tasks').focus();await page.keyboard.press('Control+b');
 await expect(page.getByRole('button',{name:'Hide project sidebar'})).toBeVisible();
 await page.getByRole('button',{name:'Filters',exact:true}).click();await page.getByLabel('Filter scope').selectOption('active');
 await page.keyboard.press('Escape');await expect(page.getByRole('group',{name:'Task filters'})).toBeHidden();
 await expect(page.getByRole('button',{name:'Filters',exact:true})).toBeFocused();
 await expect(page.locator('.filter-count')).toHaveText('1');
 await page.getByRole('button',{name:'Board actions',exact:true}).click();
 await expect(page.getByRole('button',{name:'Import documents',exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:'Adopt board…',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Areas & milestones',exact:true}).click();
 await expect(page.getByRole('dialog')).toBeVisible();await expect(page.getByRole('button',{name:'Board actions',exact:true})).toHaveAttribute('aria-expanded','false');
 await page.getByRole('button',{name:'Close settings'}).click();
 await page.getByRole('button',{name:'Board actions',exact:true}).click();await page.getByLabel('Search tasks').click();
 await expect(page.getByRole('group',{name:'Board actions',exact:true})).toBeHidden();
 await page.getByRole('button',{name:'Filters',exact:true}).click();await page.getByRole('button',{name:'Reset',exact:true}).click();await page.keyboard.press('Escape');
 await page.getByRole('button',{name:'Hide project sidebar'}).click();
 await mkdir('/tmp/project-dashboard-ui-preview',{recursive:true,mode:0o700});
 await page.screenshot({path:'/tmp/project-dashboard-ui-preview/console-dark.png',animations:'disabled'});
 await page.getByRole('button',{name:'Toggle theme'}).click();await expect(page.locator('html')).toHaveAttribute('data-theme','light');
 await expect(page.locator('.svelte-flow')).toHaveClass(/light/);await page.screenshot({path:'/tmp/project-dashboard-ui-preview/console-light.png',animations:'disabled'});
 expect(await snapshot()).toEqual(before);expect(before.board.adoption).toBe('mirror');
 await page.setViewportSize({width:390,height:844});await page.reload();
 await expect(page.getByRole('button',{name:'List',exact:true})).toHaveClass(/active/);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
 expect((await page.locator('.view-area').boundingBox())!.y).toBeLessThanOrEqual(125);
 await page.getByRole('button',{name:'Filters',exact:true}).click();await expect(page.getByLabel('Filter status')).toBeVisible();
 const panel=(await page.locator('.filter-panel').boundingBox())!;expect(panel.x).toBeGreaterThanOrEqual(0);expect(panel.x+panel.width).toBeLessThanOrEqual(390);
 await page.keyboard.press('Escape');await page.getByRole('button',{name:'Show project sidebar'}).click();
 await expect(page.getByRole('navigation',{name:'Projects'})).toBeVisible();
 await page.getByRole('button',{name:'Hide project sidebar'}).click();
 await page.screenshot({path:'/tmp/project-dashboard-ui-preview/console-mobile.png',animations:'disabled'});
 expect(await snapshot()).toEqual(before);expect(errors).toEqual([]);
});
